async function ensureColumn() {
  try {
    await pool.query(
      `ALTER TABLE booking_checkup_items ADD COLUMN clinical_significance VARCHAR(500) NULL COMMENT '检查意义/临床意义'`
    );
    console.log('  ✅ 已添加 clinical_significance 列');
  } catch (err) {
    if (err.errno === 1060) {
      console.log('  ℹ️  clinical_significance 列已存在，跳过');
    } else {
      throw err;
    }
  }
}

async function main() {
  console.log('\n🔬 体检项目体检意义批量更新 v2');
  console.log('═'.repeat(60));

  console.log('\n📋 Step 1: 检查并添加 clinical_significance 列...');
  await ensureColumn();

  console.log('\n📋 Step 2: 批量更新体检意义数据...');

  // 先清空旧的兜底数据
  try {
    await pool.query(
      `UPDATE booking_checkup_items SET clinical_significance = NULL WHERE clinical_significance = '用于相关疾病的筛查与诊断'`
    );
    console.log('  🧹 已清空旧兜底数据');
  } catch (err) {
    console.log(`  ⚠️  清理旧数据: ${err.message}`);
  }

  let success = 0;
  let failed = 0;
  const failedList = [];

  for (const [name, category, desc] of mappings) {
    const sql = `UPDATE booking_checkup_items SET clinical_significance = ? WHERE name = ? AND category = ? AND status != 0`;
    const values = [desc, name, category];

    try {
      const [result] = await pool.query(sql, values);
      if (result.affectedRows > 0) {
        success++;
      } else {
        failed++;
        failedList.push({ name, category, reason: '未匹配到记录' });
      }
    } catch (err) {
      failed++;
      failedList.push({ name, category, reason: err.message });
    }
  }

  // 兜底：未命中的
  try {
    const [result] = await pool.query(
      `UPDATE booking_checkup_items SET clinical_significance = '用于体检筛查与疾病辅助诊断' WHERE clinical_significance IS NULL AND status != 0`
    );
    if (result.affectedRows > 0) {
      console.log(`\n  兜底：${result.affectedRows} 条未命中记录已设置通用描述`);
    }
  } catch (err) {
    console.log(`\n  兜底更新失败: ${err.message}`);
  }

  console.log('\n📊 更新结果：');
  console.log('─'.repeat(60));
  console.log(`  ✅ 成功：${success} 条`);
  if (failedList.length > 0) {
    console.log(`  ❌ 失败：${failed} 条`);
    console.log('\n  失败详情：');
    for (const f of failedList) {
      console.log(`    - [${f.category}] ${f.name} → ${f.reason}`);
    }
  } else {
    console.log(`  ❌ 失败：0 条`);
  }
  console.log('─'.repeat(60));
  console.log(`  总计：${mappings.length} 条映射\n`);

  await pool.end();

  if (failedList.length === 0) {
    console.log('✅ 全部更新完成！\n');
  } else {
    console.log(`⚠️  有 ${failedList.length} 条未匹配，请检查项目名称或分类是否一致\n`);
  }
}

main().catch(err => {
  console.error('执行失败:', err);
  process.exit(1);
});
