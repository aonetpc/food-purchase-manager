-- ============================================================
-- 077: 体检项目分类重映射 → 新7大类
-- 新分类（7类，UI顶部7个Tab）：
--   体格检查 / 实验室 / 影像检查 / 功能检查 / 肿瘤筛查 / 妇科专项 / 特色加项
-- 执行策略：UPDATE booking_checkup_items.category CASE WHEN ...
--           仅 UPDATE，不新增/删除记录，幂等安全。
-- ============================================================

UPDATE booking_checkup_items
SET category = CASE
  -- ============ 妇科专项 ============
  WHEN name IN (
    '白带常规','宫颈脱落细胞检查','TCT（液基薄层细胞）',
    '人乳头瘤病毒（HPV16/18）定量','人乳头瘤病毒（HPV-23）定性',
    '电子阴道镜'
  ) THEN '妇科专项'

  -- ============ 肿瘤筛查 ============
  WHEN name IN (
    '甲胎蛋白定量（AFP）','甲胎蛋白定性（CEA）','甲胎蛋白定性',
    '癌胚抗原定量（AFP）','癌胚抗原定性（CEA）','癌胚抗原定量',
    '糖类抗原199（CA199）','糖类抗原724（CA724）','糖类抗原153（CA153）',
    '糖类抗原125（CA125）','非小细胞肺癌相关抗原（CA211）','非小细胞肺癌相关抗原（CYFRA211）',
    '糖类抗原50（CA50）','骨钙素（OST）','人附睾蛋白（HE4）',
    '胃泌素释放前体（proGRP）','鳞状细胞癌相关抗体（SCC）','糖类抗原242（CA242）',
    '神经元特异性烯醇化酶（NSE）','总前列腺特异性抗原（T-PSA）',
    '游离前列腺特异性抗原（F-PSA）','β-绒毛膜促性腺激素（β-HCG）',
    '前列腺肿瘤两项筛选（PSA+FPSA）','肿瘤5项（男）/（女）','肿瘤6项（男）/（女）',
    '蛋白芯片7项（男）/（女）','蛋白芯片10项（男）/（女）',
    '肿瘤指标11项（男）','肿瘤指标(女)11项','肿瘤指标(女)11项（罗）',
    '肿瘤指标全套(男)15项（罗）','肿瘤指标全套(女)15项（罗）',
    '恶性肿瘤特异性生长因子（TSGF）','胸苷激酶1(TK1)（外）',
    '血管内皮生长因子（VEGF）（外）','肺癌SHOX2+RASSF1A+PTGER4基因甲基化检测(外）',
    'Septin9肠癌基因检测（外）','RNF180/Septin9基因甲基化（胃癌）早筛和辅助诊断检测（外）',
    'Reprimo/SDC2/TCF4胃癌三基因甲基化（外）','降钙素（外）'
  ) THEN '肿瘤筛查'

  -- ============ 功能检查 ============
  WHEN name IN (
    '心电图（12导常规）','24小时动态心电图','24小时动态血压',
    'C14呼气试验','C13呼气试验','电子阴道镜','人体成分分析',
    '动脉硬化检测','肺功能检查','骨密度','经颅多普勒TCD'
  ) THEN '功能检查'

  -- ============ 影像检查 ============
  WHEN name LIKE '彩超-%'
    OR name IN (
      '数字DR摄片/部位','出片费（DR+CT）','CT部位（不含片）','CT动态分析',
      '电子直乙肠镜'
    )
    OR category = '影像'
  THEN '影像检查'

  -- ============ 体格检查 ============
  WHEN name IN (
    '一般检查','内科','外科（男、女）','眼科','眼压','裂隙灯检查',
    '耳鼻喉科','口腔科','妇科常规','一般检查(身高/体重/BMI)','血压',
    '眼科检查'
  ) OR category = '一般检查' OR category = '专科'
  THEN '体格检查'

  -- ============ 特色加项（外送、特色、过敏原、维D等） ============
  WHEN name IN (
    '抗缪勒管激素（外）','25-羟基维生素D（总）（外）','25-羟基维生素D(D2/D3)（外）',
    '过敏源检测（混合16项）','过敏原检测（混合28项）'
  ) THEN '特色加项'

  -- ============ 其余 → 实验室（原"化验"基本全入实验室）============
  WHEN category = '化验'
    OR name LIKE '%功能%项' OR name LIKE '%肝功%' OR name LIKE '%肾功%'
    OR name LIKE '%血脂%' OR name LIKE '%血糖%' OR name LIKE '糖化%'
    OR name LIKE '%常规%' OR name LIKE '%全套' OR name LIKE '%组合'
    OR name LIKE '%蛋白%' OR name LIKE '%抗体%' OR name LIKE '%抗原%'
    OR name LIKE '凝血%' OR name LIKE '电解质%' OR name LIKE '微量元素%'
  THEN '实验室'

  ELSE category  -- 其余保持不变（兜底）
END
WHERE 1 = 1;
